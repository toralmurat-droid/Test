/**
 * Bakes the Crown Keep's 3D walls (paint/crownWalls3d.ts) into client/public/assets/hd/props/cr_walls3d.png, one
 * frame per wall piece the Keep's map uses, CRW.cols frames a row, and writes their keys in frame order to
 * client/src/crownWallFrames.ts. Re-run after the Keep's walls change on the map: `npx tsx tools/art/bake-crown-walls.ts`
 * (PREVIEW=file.png also writes a 3x preview of the sheet).
 */
import { writeFileSync } from "node:fs";
import { createCanvas } from "@napi-rs/canvas";
import { OBJECTS } from "../../shared/map";
import { CRW, wallKeys } from "../../client/src/crownWalls";
import { renderWall } from "./paint/crownWalls3d";

const obj = (x: number, y: number) => OBJECTS[y]?.[x] ?? -1;
const keys = wallKeys(OBJECTS, obj);
const cols = Math.min(CRW.cols, keys.length), rows = Math.ceil(keys.length / CRW.cols);
const cv = createCanvas(CRW.w * cols, CRW.h * rows), c = cv.getContext("2d"), img = c.createImageData(cv.width, cv.height);
keys.forEach((k, f) => {
  const t0 = Date.now(), buf = renderWall(k), fx = (f % CRW.cols) * CRW.w, fy = Math.floor(f / CRW.cols) * CRW.h;
  for (let y = 0; y < CRW.h; y++) for (let x = 0; x < CRW.w; x++) {
    const v = buf[y * CRW.w + x], i = ((fy + y) * cv.width + fx + x) * 4;
    img.data[i] = (v >> 16) & 255; img.data[i + 1] = (v >> 8) & 255; img.data[i + 2] = v & 255; img.data[i + 3] = v >>> 24;
  }
  console.log(k, `${Date.now() - t0} ms`);
});
c.putImageData(img, 0, 0);
writeFileSync(`client/public/assets/hd/props/${CRW.key}.png`, cv.toBuffer("image/png"));
writeFileSync("client/src/crownWallFrames.ts", `// Generated by tools/art/bake-crown-walls.ts: the frames of client/public/assets/hd/props/${CRW.key}.png, in order.\nexport const CROWN_WALL_FRAMES: readonly string[] = [\n${keys.map((k) => `  "${k}",`).join("\n")}\n];\n`);
if (process.env.PREVIEW) {
  const S = 3, pv = createCanvas(cv.width * S, cv.height * S), pc = pv.getContext("2d");
  pc.fillStyle = "#5a5650"; pc.fillRect(0, 0, pv.width, pv.height); pc.imageSmoothingEnabled = false;
  pc.drawImage(cv, 0, 0, pv.width, pv.height);
  writeFileSync(process.env.PREVIEW, pv.toBuffer("image/png"));
}
console.log(`${keys.length} frames`);
